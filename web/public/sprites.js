// 默认配色（LLM 未生成时使用）
const DEFAULT_COLORS = {
  skin:    '#FFDDB5',
  hair:    '#5A3E2B',
  dark:    '#2A2A2A',
  clothes: '#6B5BCD',
  blush:   '#FF8FA0',
};

// 颜色索引表（数组值 → 颜色 key）
const COLOR_INDEX = {
  1: 'skin',
  2: 'hair',
  3: 'dark',
  4: 'clothes',
  5: 'blush',
};

// 渲染函数：将精灵绘制到 canvas
function drawSprite(canvas, expression, pixelSize, colors) {
  const template = SPRITE_TEMPLATES[expression] || SPRITE_TEMPLATES.idle;
  const pal      = Object.assign({}, DEFAULT_COLORS, colors);
  const rows = template.length;
  const cols = template[0].length;

  canvas.width  = cols * pixelSize;
  canvas.height = rows * pixelSize;

  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, canvas.width, canvas.height);

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const v = template[r][c];
      if (v === 0) continue;
      ctx.fillStyle = pal[COLOR_INDEX[v]] || '#000';
      ctx.fillRect(c * pixelSize, r * pixelSize, pixelSize, pixelSize);
    }
  }
}
